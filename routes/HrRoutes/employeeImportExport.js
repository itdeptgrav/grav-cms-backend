router.get("/export", EmployeeAuthMiddlewear, async (req, res) => {
    try {
        const { department, status, search } = req.query;

        let filter = {};
        if (department && department !== "all") filter.department = department;
        if (status && status !== "all") filter.status = status;
        if (search) {
            filter.$or = [
                { firstName: { $regex: search, $options: "i" } },
                { lastName: { $regex: search, $options: "i" } },
                { email: { $regex: search, $options: "i" } },
                { biometricId: { $regex: search, $options: "i" } },
            ];
        }

        const rawEmployees = await Employee.find(filter).sort({ createdAt: -1 }).lean();

        // Salary is stored encrypted ("enc:a1b2…"). Writing the raw field put
        // ciphertext in the Gross Salary column, and every formula that reads
        // it — Basic, HRA, EPF, ESIC, Net, CTC — then showed #VALUE! down the
        // whole sheet.
        const employees = decryptEmployeeDocs(rawEmployees);

        const cfg = await SalaryConfig.getSingleton();

        const built = await buildEmployeeWorkbook({ employees, cfg, mode: "export" });

        const dateStr = new Date().toISOString().split("T")[0];

        if (String(req.query.format || "").toLowerCase() === "csv") {
            res.setHeader("Content-Disposition", `attachment; filename=employee_export_${dateStr}.csv`);
            res.setHeader("Content-Type", "text/csv; charset=utf-8");
            return res.send(built.csv);
        }

        assertRealWorkbook(built.buffer, "export");

        res.setHeader("Cache-Control", "no-store, no-cache, must-revalidate");
        res.setHeader("Content-Disposition", `attachment; filename=employee_export_${dateStr}.xlsx`);
        res.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
        res.setHeader("Content-Length", built.buffer.length);
        return res.send(built.buffer);

    } catch (err) {
        console.error("Export error:", err);
        res.status(500).json({ success: false, message: err.message || "Export failed." });
    }
});

