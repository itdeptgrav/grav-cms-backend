const parseDate = (val) => {
    if (!val) return undefined;
    if (val instanceof Date) return isNaN(val.getTime()) ? undefined : val;
    if (typeof val === "number") {
        const p = XLSX.SSF.parse_date_code(val);
        return p ? new Date(p.y, p.m - 1, p.d) : undefined;
    }
    const s = String(val).trim();
    if (!s) return undefined;
    const m1 = s.match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})$/);
    if (m1) return new Date(`${m1[3]}-${m1[2].padStart(2, "0")}-${m1[1].padStart(2, "0")}`);
    const m2 = s.match(/^(\d{1,2})-(\d{1,2})-(\d{4})$/);
    if (m2) return new Date(`${m2[3]}-${m2[2].padStart(2, "0")}-${m2[1].padStart(2, "0")}`);
    const d = new Date(s);
    return isNaN(d.getTime()) ? undefined : d;
};

const toNum = (v) => {
    if (typeof v === "number") return isNaN(v) ? 0 : v;
    const s = String(v || "").replace(/[,₹\s]/g, "");
    const n = Number(s);
    return isNaN(n) ? 0 : n;
};

const toBool = (v) => {
    if (typeof v === "boolean") return v;
    return String(v || "").toLowerCase().trim() === "yes";
};

/**
 * Yes/No that stays UNDECIDED when the cell is empty.
 *
 * toBool() turns a blank cell into `false`, which is right on a create and
 * destructive on an update: re-importing a sheet where "Is Director" was left
 * empty would quietly demote every director. undefined means "the sheet has no
 * opinion", and the merge skips it.
 */
const optBool = (v) => {
    if (typeof v === "boolean") return v;
    const s = String(v ?? "").trim().toLowerCase();
    if (!s) return undefined;
    if (["yes", "y", "true", "1"].includes(s)) return true;
    if (["no", "n", "false", "0"].includes(s)) return false;
    return undefined;
};

const isBlankValue = (v) =>
    v === undefined ||
    v === null ||
    (typeof v === "string" && v.trim() === "");

const sameValue = (a, b) => {
    if (a instanceof Date || b instanceof Date) {
        const ta = a instanceof Date ? a.getTime() : new Date(a).getTime();
        const tb = b instanceof Date ? b.getTime() : new Date(b).getTime();
        return ta === tb;
    }
    if (typeof a === "number" || typeof b === "number") return Number(a) === Number(b);
    if (typeof a === "boolean" || typeof b === "boolean") return Boolean(a) === Boolean(b);
    return String(a ?? "").trim() === String(b ?? "").trim();
};

/**
 * Work out what an import row would actually change on an employee already on
 * record.
 *
 * Two rules, both of which exist so a partially-filled sheet is safe to import:
 *   - a blank cell is silence, not an instruction to clear the field
 *   - a value equal to what is stored is not a change, so it is not reported
 *
 * Nested objects are walked leaf by leaf and patched with dotted paths. Setting
 * `bankDetails` wholesale would wipe the branch name whenever the sheet left
 * that column empty.
 */
const buildPatch = (existing, incoming, prefix = "", patch = {}, changes = []) => {
    for (const [key, value] of Object.entries(incoming || {})) {
        if (key.startsWith("_")) continue;

        const path = prefix ? `${prefix}.${key}` : key;
        const current = existing?.[key];

        if (
            value &&
            typeof value === "object" &&
            !(value instanceof Date) &&
            !Array.isArray(value)
        ) {
            buildPatch(current || {}, value, path, patch, changes);
            continue;
        }

        if (isBlankValue(value)) continue;
        if (current !== undefined && sameValue(current, value)) continue;

        patch[path] = value;
        changes.push({ field: path, from: current ?? "", to: value });
    }

    return { patch, changes };
};

