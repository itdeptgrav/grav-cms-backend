// ROUTE 3: CONFIRM IMPORT
// ─────────────────────────────────────────────────────────────────────────────
// A spreadsheet import is a bulk edit to employee records, and the one place
// where a mistake reaches hundreds of people at once. It gets its own section
// so it can be read as a list of imports rather than being scattered through
// the Employees history alongside single edits.
const { recordChange } = require("../../services/changeLog");

router.post("/import/confirm", EmployeeAuthMiddlewear, async (req, res) => {
    try {
        const { user } = req;
        const { rows } = req.body;
        if (!Array.isArray(rows) || rows.length === 0) {
            return res.status(400).json({ success: false, message: "No rows to import." });
        }

        const results = {
            created: 0,
            updated: 0,
            unchanged: 0,
            failed: 0,
            errors: [],
            updatedDetails: [],
        };

        // Re-planned server-side. The client sends back what preview gave it,
        // but the decision to create or update — and the patch that goes with
        // it — is not something to take on trust from a request body.
        const planned = await planRows(rows);

        for (const row of planned) {
            try {
                if (row._errors && row._errors.length > 0) {
                    results.failed++;
                    results.errors.push({ employeeNum: row._employeeNum, errors: row._errors });
                    continue;
                }

                /* ── UPDATE ─────────────────────────────────────────────── */
                if (row._mode === "update") {
                    const changed = Object.keys(row._patch || {});

                    if (changed.length === 0) {
                        results.unchanged++;
                        continue;
                    }

                    // Loaded and saved as a document rather than updateOne'd.
                    // updateOne skips the model's pre-save hook, which is what
                    // re-encrypts salary and recalculates the derived fields —
                    // a $set would have written plaintext numbers into columns
                    // every other part of the system expects to be encrypted.
                    const doc = await Employee.findById(row._existingId);
                    if (!doc) {
                        results.failed++;
                        results.errors.push({
                            employeeNum: row._employeeNum,
                            biometricId: row.biometricId,
                            errors: ["Employee disappeared between preview and import"],
                        });
                        continue;
                    }

                    for (const [fieldPath, value] of Object.entries(row._patch)) {
                        doc.set(fieldPath, value);
                    }
                    doc.updatedBy = user?.id;

                    await doc.save();

                    results.updated++;
                    results.updatedDetails.push({
                        employeeNum: row._employeeNum,
                        name: row._existingName,
                        biometricId: row.biometricId,
                        matchedBy: row._matchedBy,
                        fields: changed,
                    });
                    continue;
                }

                /* ── CREATE ─────────────────────────────────────────────── */
                const tempPass = Math.random().toString(36).slice(-8);
                const empData = toEmployeeData(row);

                // Create-time defaults. These deliberately do NOT run on update:
                // defaulting there would overwrite whatever is already on record
                // every time a column was left blank.
                empData.workLocation = empData.workLocation || "GRAV Clothing";
                empData.probationPeriod = empData.probationPeriod || 0;
                empData.isPhysicallyChallenged = empData.isPhysicallyChallenged || false;
                empData.isDirector = empData.isDirector || false;
                empData.isInternational = empData.isInternational || false;
                empData.needsToOperate = empData.needsToOperate || false;

                // A new joiner's permanent address defaults to their current one
                // unless the sheet gave a separate permanent address.
                const current = empData.address?.current;
                if (current && !empData.address.permanent?.street) {
                    empData.address.permanent = { ...current };
                }

                empData.password = tempPass;
                empData.temporaryPassword = tempPass;
                empData.createdBy = user?.id;
                empData.createdAt = new Date();

                const emp = new Employee(empData);
                await emp.save();
                results.created++;
            } catch (err) {
                results.failed++;
                const msg = err.code === 11000
                    ? `Duplicate: ${Object.keys(err.keyPattern || {}).join(", ")} already exists`
                    : err.message || "Unknown error";
                results.errors.push({
                    employeeNum: row._employeeNum,
                    biometricId: row.biometricId,
                    name: [row.firstName, row.lastName].filter(Boolean).join(" "),
                    errors: [msg],
                });
            }
        }

        const parts = [`${results.created} created`, `${results.updated} updated`];
        if (results.unchanged) parts.push(`${results.unchanged} already up to date`);
        if (results.failed) parts.push(`${results.failed} failed`);

        // Named per employee, with the fields the import touched on each. A
        // count alone cannot answer the question this log exists for: an
        // employee whose designation changed on the 14th needs to be able to
        // find that it was an import that did it, and which columns it wrote.
        await recordChange(req, {
            departmentSlug: "hr",
            section: "hr:employee-import",
            entity: "employee-import",
            entityId: new Date().toISOString(),
            entityLabel: `Import of ${rows.length} row(s)`,
            action: "import",
            origin: "import",
            summary:
                `Imported an employee spreadsheet of ${rows.length} row(s): ${parts.join(", ")}. ` +
                (results.failed
                    ? `The ${results.failed} failed row(s) changed nothing.`
                    : "Every row was processed."),
            fields: results.updatedDetails.slice(0, 120).map((d) => ({
                path: d.biometricId || String(d.employeeNum),
                label: `${d.name || d.biometricId} (matched by ${d.matchedBy})`,
                to: d.fields.join(", "),
                kind: "changed",
            })),
        });

        res.json({
            success: true,
            message: `Import complete: ${parts.join(", ")}.`,
            data: results,
        });
    } catch (err) {
        console.error("Import confirm error:", err);
        res.status(500).json({ success: false, message: err.message || "Import failed." });
    }
});

