// ROUTE 1: DOWNLOAD TEMPLATE
//
// The template used to be a static file shipped in the repo. That file was
// 0 bytes, which is why Excel refused it with "the file format or file
// extension is not valid" — an empty file is not a zip, and .xlsx is a zip.
//
// It is now generated by the SAME builder as /export, so two problems go away
// at once: it cannot be missing or truncated, and the template's columns are
// by construction identical to what export produces. Export → edit → import
// round-trips because there is only one layout in the codebase.
//
// ?format=csv returns the same columns as plain CSV, for anyone whose Excel is
// unhappy with xlsx.
// ─────────────────────────────────────────────────────────────────────────────
router.get("/template", EmployeeAuthMiddlewear, async (req, res) => {
    try {
        const cfg = await SalaryConfig.getSingleton();
        const wantsCsv = String(req.query.format || "").toLowerCase() === "csv";

        const built = await buildEmployeeWorkbook({
            employees: [],
            cfg,
            mode: "template",
            // Enough blank rows to type into, each already carrying the salary
            // formulas so Basic/HRA/EPF/CTC fill themselves in as Gross is typed.
            blankRows: 200,
        });

        // This URL has no query string, so it is trivially cacheable — and the
        // version that used to live here returned a 0-byte body. A browser or
        // proxy holding that response will keep handing out the broken file
        // long after the server is fixed, which looks exactly like the server
        // still being broken.
        res.setHeader("Cache-Control", "no-store, no-cache, must-revalidate");
        res.setHeader("Pragma", "no-cache");
        res.setHeader("Expires", "0");

        if (wantsCsv) {
            res.setHeader("Content-Disposition", "attachment; filename=employee_import_template.csv");
            res.setHeader("Content-Type", "text/csv; charset=utf-8");
            return res.send(built.csv);
        }

        // Never ship a body that is not a real workbook. An .xlsx is a zip, so
        // it must start with "PK". Sending a truncated or empty body produces
        // Excel's "the file format or file extension is not valid", with
        // nothing in the logs to explain it — a JSON error is far easier to act
        // on than a corrupt download.
        assertRealWorkbook(built.buffer, "template");

        res.setHeader("Content-Disposition", "attachment; filename=employee_import_template.xlsx");
        res.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
        res.setHeader("Content-Length", built.buffer.length);
        return res.send(built.buffer);
    } catch (err) {
        console.error("Template download error:", err);
        res.status(500).json({ success: false, message: err.message || "Could not build the template." });
    }
});

