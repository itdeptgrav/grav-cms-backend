/**
 * Build the employee workbook from the shipped template.
 *
 * ONE builder for both the blank template and the populated export — that is
 * the point. When they were separate, the template drifted from what export
 * produced and an exported file could not be edited and re-imported.
 *
 * Two things forced a rewrite from the `xlsx` package to ExcelJS:
 *
 *   1. `xlsx` (the community build) SILENTLY DISCARDS cell styles on write.
 *      Every `s:` this file used to set was thrown away, which is why the
 *      download arrived unstyled no matter what the code asked for.
 *   2. The theme is not worth re-describing in code. The real template lives
 *      at assets/employee_import_template.xlsx and is loaded here, so
 *      restyling means editing that file — banner, section colours, borders,
 *      widths, freeze panes and the Instructions sheet all come along for
 *      free and cannot drift from what anyone expects to see.
 *
 * Salary formulas are regenerated for every row rather than copied from the
 * asset. The asset's first data row carried a broken set — it read Basic from
 * the row BELOW it, and Food Allowance, ESIC (Employer) and CTC were copies of
 * neighbouring cells — so copying would have propagated that into every row of
 * every export.
 *
 * @param employees  rows to write; empty for a template
 * @param cfg        salary config, drives the in-sheet formulas
 * @param mode       "template" | "export" — only changes the banner wording
 * @param blankRows  empty rows to pre-fill with formulas (template only)
 * @returns { buffer, csv }
 */
async function buildEmployeeWorkbook({ employees = [], cfg, mode = "export", blankRows = 0 }) {
    const isTemplate = mode === "template";

    // Salary arrives here already decrypted — callers must run the rows through
    // decryptEmployeeDocs() first. Handing over raw documents used to write the
    // "enc:…" cipher string into Gross Salary, which turned every formula that
    // reads it into #VALUE! all the way down the sheet. Fail loudly rather than
    // producing that file again.
    const stillEncrypted = employees.find(
        (e) => typeof e?.salary?.gross === "string" && e.salary.gross.startsWith("enc:"),
    );
    if (stillEncrypted) {
        throw new Error(
            "Salary is still encrypted — call decryptEmployeeDocs() on the employees " +
            "before building the workbook.",
        );
    }

    // A checked-in binary is easy to lose in a deploy that only ships source.
    // Say so plainly instead of letting ExcelJS throw an ENOENT that reaches
    // the user as a generic 500.
    if (!fs.existsSync(TEMPLATE_PATH)) {
        throw new Error(
            `Template asset missing at ${TEMPLATE_PATH}. It must be deployed with the code — ` +
            "the whole workbook design lives in that file.",
        );
    }

    const wb = new ExcelJS.Workbook();
    await wb.xlsx.readFile(TEMPLATE_PATH);

    const ws = wb.getWorksheet("Employee Import") || wb.worksheets[0];
    if (!ws) throw new Error("Template asset has no 'Employee Import' sheet.");

    /* ── Locate the header row rather than trusting an offset ─────────────── */
    const knownHeaders = new Set(COLUMNS.map((c) => normalizeHeader(c.header)));
    let headerRowNum = 3;
    let bestHits = 0;

    for (let r = 1; r <= Math.min(10, ws.rowCount); r++) {
        let hits = 0;
        ws.getRow(r).eachCell({ includeEmpty: false }, (cell) => {
            if (knownHeaders.has(normalizeHeader(cell.text))) hits++;
        });
        if (hits > bestHits) { bestHits = hits; headerRowNum = r; }
    }

    const dataStart = headerRowNum + 1;

    /* ── header text -> column number ─────────────────────────────────────── */
    const colOf = new Map();
    ws.getRow(headerRowNum).eachCell({ includeEmpty: false }, (cell, colNumber) => {
        colOf.set(normalizeHeader(cell.text), colNumber);
    });

    const copyStyle = (cell) =>
        cell && cell.style ? JSON.parse(JSON.stringify(cell.style)) : {};

    /* ── Capture the template's look before clearing anything ─────────────── */
    // Appended columns, and every row past the ones the asset already has, are
    // styled from these. Without them a 500-employee export would look like the
    // template for 100 rows and like raw Excel for the other 400.
    const templateColumnCount = ws.columnCount;
    const firstDataRow = ws.getRow(dataStart);
    const dataStyleByCol = new Map();
    for (let c = 1; c <= templateColumnCount; c++) {
        dataStyleByCol.set(c, copyStyle(firstDataRow.getCell(c)));
    }
    const headerStyle = copyStyle(ws.getRow(headerRowNum).getCell(1));
    const sectionStyle = copyStyle(ws.getRow(headerRowNum - 1).getCell(1));
    const plainDataStyle = dataStyleByCol.get(1) || {};

    /* ── Append the extra columns, in the template's own visual language ──── */
    // These carry fields with no home in the standard block: passport, voter
    // ID, permanent address, managers. They go into the TEMPLATE as well as the
    // export, so the two stay structurally identical — the thing that made
    // export → edit → re-import unreliable in the first place.
    const extraStartCol = COLUMNS.length + 1;
    const totalCols = COLUMNS.length + EXTRA_EXPORT_COLS.length;

    EXTRA_EXPORT_COLS.forEach((col, i) => {
        const c = extraStartCol + i;
        const cell = ws.getRow(headerRowNum).getCell(c);
        cell.value = col.header;
        cell.style = {
            ...headerStyle,
            fill: {
                type: "pattern",
                pattern: "solid",
                fgColor: { argb: "FFEFF6FF" },
                bgColor: { argb: "FFDBEAFE" },
            },
            font: { ...(headerStyle.font || {}), color: { argb: "FF1E3A8A" } },
        };
        ws.getColumn(c).width = 18;
        colOf.set(normalizeHeader(col.header), c);
        dataStyleByCol.set(c, plainDataStyle);
    });

    // The banner spans the full width; the section strip gets an EXTRA INFO
    // block over the appended columns.
    try { ws.unMergeCells(1, 1, 1, templateColumnCount); } catch (e) { /* wasn't merged */ }
    ws.mergeCells(1, 1, 1, totalCols);
    ws.getRow(1).getCell(1).value = isTemplate
        ? "EMPLOYEE IMPORT TEMPLATE  •  Fields marked * are required  •  Enter Gross Salary — all other salary fields auto-calculate  •  Re-importing an existing Biometric ID updates that employee instead of creating a duplicate"
        : "EMPLOYEE EXPORT  •  Fields marked * are required on re-import  •  Enter Gross Salary — all other salary fields auto-calculate  •  Edit and re-import this file to update these employees";

    if (EXTRA_EXPORT_COLS.length > 0) {
        const banner = ws.getRow(headerRowNum - 1).getCell(extraStartCol);
        banner.value = "EXTRA INFO";
        banner.style = { ...sectionStyle };
        ws.mergeCells(headerRowNum - 1, extraStartCol, headerRowNum - 1, totalCols);
    }

    /* ── Clear the asset's own data rows ──────────────────────────────────── */
    if (ws.rowCount >= dataStart) {
        ws.spliceRows(dataStart, ws.rowCount - dataStart + 1);
    }

    /* ── Salary formulas ──────────────────────────────────────────────────── */
    const letterOf = (header) => {
        const c = colOf.get(normalizeHeader(header));
        return c ? ws.getColumn(c).letter : null;
    };

    const L = {
        gross: letterOf("Gross Salary"),
        basic: letterOf("Basic Salary"),
        hra: letterOf("HRA"),
        epfEE: letterOf("EPF (Employee)"),
        esicEE: letterOf("ESIC (Employee)"),
        totDed: letterOf("Total Deductions"),
        net: letterOf("Net Salary"),
        epfER: letterOf("EPF (Employer)"),
        esicER: letterOf("ESIC (Employer)"),
        food: letterOf("Food Allowance"),
        ctc: letterOf("Employer Cost (CTC)"),
    };

    const basicPct = (cfg.basicPct ?? 50) / 100;
    const hraPct = (cfg.hraPct ?? 50) / 100;
    const eepfPct = (cfg.eepfPct ?? 12) / 100;
    const epfCap = cfg.epfCapAmount ?? 1800;
    const esiLimit = cfg.esiWageLimit ?? 21000;
    const eeEsicPct = (cfg.eeEsicPct ?? 0.75) / 100;
    const erEsicPct = (cfg.erEsicPct ?? 3.25) / 100;
    const foodAmt = cfg.foodAllowance ?? 1600;

    // Every formula is guarded with IF(Gross="","",…) so a blank template row
    // stays visually empty instead of showing a column of zeroes.
    const formulasFor = (R) => ({
        [L.basic]: `IF(${L.gross}${R}="","",ROUND(${L.gross}${R}*${basicPct},0))`,
        [L.hra]: `IF(${L.gross}${R}="","",ROUND(${L.gross}${R}*${hraPct},0))`,
        [L.epfEE]: `IF(${L.basic}${R}="","",ROUND(MIN(${L.basic}${R}*${eepfPct},${epfCap}),0))`,
        [L.esicEE]: `IF(${L.basic}${R}="","",IF(${L.basic}${R}<=${esiLimit},CEILING(${L.basic}${R}*${eeEsicPct},1),0))`,
        [L.totDed]: `IF(${L.epfEE}${R}="","",${L.epfEE}${R}+IF(${L.esicEE}${R}="",0,${L.esicEE}${R}))`,
        [L.net]: `IF(${L.gross}${R}="","",MAX(${L.gross}${R}-IF(${L.totDed}${R}="",0,${L.totDed}${R}),0))`,
        [L.epfER]: `IF(${L.epfEE}${R}="","",${L.epfEE}${R})`,
        [L.esicER]: `IF(${L.basic}${R}="","",IF(${L.basic}${R}<=${esiLimit},CEILING(${L.basic}${R}*${erEsicPct},1),0))`,
        [L.food]: `IF(${L.gross}${R}="","",${foodAmt})`,
        [L.ctc]: `IF(${L.gross}${R}="","",${L.gross}${R}+IF(${L.epfER}${R}="",0,${L.epfER}${R})+IF(${L.esicER}${R}="",0,${L.esicER}${R})+IF(${L.food}${R}="",0,${L.food}${R}))`,
    });

    const FORMULA_HEADERS = new Set(
        ["Basic Salary", "HRA", "EPF (Employee)", "ESIC (Employee)", "Total Deductions",
            "Net Salary", "EPF (Employer)", "ESIC (Employer)", "Food Allowance",
            "Employer Cost (CTC)"].map(normalizeHeader)
    );

    /* ── Write the rows ───────────────────────────────────────────────────── */
    const writeRow = (offset, employee) => {
        const emp = employee || {};
        const isBlankRow = !employee;
        const rowNum = dataStart + offset;
        const row = ws.getRow(rowNum);

        const fatherFullName = [emp.fatherFirstName, emp.fatherMiddleName, emp.fatherLastName]
            .filter(Boolean).join(" ");

        const VALUES = {
            "Employee Name": `${emp.firstName || ""} ${emp.lastName || ""}`.trim(),
            "Title": emp.title || "",
            "Father / Husband Name": fatherFullName,
            "Gender": capFirst(emp.gender || ""),
            "Date of Birth": fmtDate(emp.dateOfBirth),
            "Mobile Number": emp.phone || "",
            "Alternate Phone": emp.alternatePhone || "",
            "Personal Email": emp.personalEmail || "",
            "Work Email": emp.email || "",
            "Marital Status": capFirst(emp.maritalStatus || ""),
            "Blood Group": emp.bloodGroup || "",
            "Nationality": emp.nationality || "",
            "Physically Challenged": isBlankRow ? "" : (emp.isPhysicallyChallenged ? "Yes" : "No"),
            "Street / Area": emp.address?.current?.street || "",
            "City": emp.address?.current?.city || "",
            "State": emp.address?.current?.state || "",
            "Pincode": emp.address?.current?.pincode || "",
            "Biometric ID": emp.biometricId || "",
            "Date of Joining": fmtDate(emp.dateOfJoining),
            "Department": emp.department || "",
            "Designation": emp.designation || "",
            "Employee Type": capFirst(emp.employmentType || ""),
            "Work Location": emp.workLocation || "",
            "Shift": emp.shift || "",
            "Is Director": isBlankRow ? "" : (emp.isDirector ? "Yes" : "No"),
            "Needs to Operate": isBlankRow ? "" : (emp.needsToOperate ? "Yes" : "No"),
            "Bank Name": emp.bankDetails?.bankName || "",
            "Account Number": emp.bankDetails?.accountNumber || "",
            "IFSC Code": emp.bankDetails?.ifscCode || "",
            "Account Type": capFirst(emp.bankDetails?.accountType || ""),
            // Blank, not 0 — the formulas key off Gross being empty, and a
            // template full of zeroes would compute a full set of zero
            // deductions instead of staying quiet.
            "Gross Salary": isBlankRow ? "" : (emp.salary?.gross || 0),
            "Aadhaar Number": emp.documents?.aadharNumber || "",
            "PAN Number": emp.documents?.panNumber || "",
            "UAN Number": emp.documents?.uanNumber || "",
            "ESI Number": emp.documents?.esicNumber || "",
            "PF Number": emp.documents?.pfNumber || "",
        };

        const rowFormulas = formulasFor(rowNum);

        COLUMNS.forEach((col) => {
            const c = colOf.get(normalizeHeader(col.header));
            if (!c) return;

            const cell = row.getCell(c);
            cell.style = dataStyleByCol.get(c) || plainDataStyle;

            if (FORMULA_HEADERS.has(normalizeHeader(col.header))) {
                const letter = ws.getColumn(c).letter;
                if (rowFormulas[letter]) cell.value = { formula: rowFormulas[letter] };
                return;
            }

            const v = VALUES[col.header];
            cell.value = v === undefined || v === "" ? null : v;
        });

        EXTRA_EXPORT_COLS.forEach((col, i) => {
            const c = extraStartCol + i;
            const cell = row.getCell(c);
            cell.style = dataStyleByCol.get(c) || plainDataStyle;
            const v = isBlankRow ? "" : col.getValue(emp);
            cell.value = v === undefined || v === "" ? null : v;
        });

        row.height = 18;
        row.commit();
    };

    employees.forEach((emp, i) => writeRow(i, emp));
    for (let i = 0; i < blankRows; i++) writeRow(employees.length + i, null);

    /* ── Widen columns to fit what is actually in them ────────────────────── */
    // The template's widths were set for a blank sheet. Once real data is in
    // it, names, emails, addresses and manager names get cut off mid-word, so
    // every column grows to its longest value. It only ever grows: the
    // template's width is the floor, so a deliberately wide column stays wide.
    const MIN_WIDTH = 10;
    const MAX_WIDTH = 46;   // past this a column stops being scannable

    for (let c = 1; c <= totalCols; c++) {
        const column = ws.getColumn(c);
        let longest = 0;

        column.eachCell({ includeEmpty: false }, (cell, rowNumber) => {
            // The row-1 banner spans every column; measuring it would blow the
            // first column out to the width of the whole sentence.
            if (rowNumber < headerRowNum) return;

            let text = cell.value;
            if (text && typeof text === "object") {
                if (text.formula !== undefined) text = text.result ?? "";
                else if (text.richText) text = text.richText.map((t) => t.text).join("");
                else if (text.text !== undefined) text = text.text;
                else text = "";
            }
            const len = String(text ?? "").length;
            if (len > longest) longest = len;
        });

        const fitted = Math.min(MAX_WIDTH, Math.max(MIN_WIDTH, longest + 3));
        column.width = Math.max(column.width || 0, fitted);
    }

    /* ── Output ───────────────────────────────────────────────────────────── */
    const buffer = Buffer.from(await wb.xlsx.writeBuffer());

    // CSV of the data only, from the header row down — the banner and section
    // strip are decoration and would leave a CSV reader with two junk lines
    // before the headers.
    //
    // Formula cells have no computed result until Excel opens the file, so the
    // auto-calculated salary columns come through blank here. Harmless: the
    // importer recalculates them from Gross anyway.
    const csvEscape = (s) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
    const csvLines = [];

    for (let r = headerRowNum; r <= ws.rowCount; r++) {
        const row = ws.getRow(r);
        const values = [];

        for (let c = 1; c <= totalCols; c++) {
            let v = row.getCell(c).value;
            if (v instanceof Date) v = fmtDate(v);
            else if (v && typeof v === "object") {
                if (v.formula !== undefined) v = v.result ?? "";
                else if (v.richText) v = v.richText.map((t) => t.text).join("");
                else if (v.text !== undefined) v = v.text;
                else v = "";
            }
            values.push(csvEscape(v === null || v === undefined ? "" : String(v)));
        }

        if (r > headerRowNum && values.every((v) => v === "")) continue;
        csvLines.push(values.join(","));
    }

    return { buffer, csv: csvLines.join("\n") };
}

