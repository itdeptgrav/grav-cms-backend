/**
 * Which row holds the column headers.
 *
 * The xlsx template puts them on row 3, under a banner and a section strip.
 * The CSV download starts at row 1, and people delete decoration rows. Rather
 * than hard-coding an offset and failing confusingly, score the first handful
 * of rows against the known column names and take the best match.
 */
const findHeaderRow = (sheet) => {
    const known = new Set(Object.keys(HEADER_MAP).map(normalizeHeader));
    const grid = XLSX.utils.sheet_to_json(sheet, {
        header: 1,
        raw: false,
        defval: "",
        blankrows: true,
    });

    let best = { row: 2, hits: 0 };
    const depth = Math.min(10, grid.length);

    for (let r = 0; r < depth; r++) {
        const hits = (grid[r] || []).reduce(
            (n, cellValue) => n + (known.has(normalizeHeader(cellValue)) ? 1 : 0),
            0,
        );
        if (hits > best.hits) best = { row: r, hits };
    }

    // Below a few matches this is guesswork; fall back to the documented layout
    // so the error message stays the familiar "wrong template" one.
    return best.hits >= 3 ? best.row : 2;
};

const parseSheet = async (buffer) => {
    const wb = XLSX.read(buffer, { type: "buffer", cellDates: true, raw: false });
    const sheet = wb.Sheets[wb.SheetNames[0]];

    // The export/template has:
    //   Row 1 = banner
    //   Row 2 = section colours
    //   Row 3 = column headers  ← range: 2 (0-based index 2 = row 3)
    //   Row 4+ = data
    // Find the header row rather than assuming it is the third. The xlsx
    // template puts it there under a banner and a section strip, but the CSV
    // download starts at the headers, and people delete decoration rows. The
    // row that matches the most known column names is the header row.
    const headerRow = findHeaderRow(sheet);

    const raw = XLSX.utils.sheet_to_json(sheet, { raw: false, defval: "", range: headerRow });
    if (!raw || raw.length === 0) {
        throw new Error("No data rows found. Make sure you are using the correct template.");
    }

    const normKeyMap = {};
    for (const key of Object.keys(raw[0])) {
        normKeyMap[normalizeHeader(key)] = key;
    }

    const standardNorms = new Set(Object.keys(HEADER_MAP).map(normalizeHeader));
    const extraColumns = [];
    for (const [normHeader, xlsxKey] of Object.entries(normKeyMap)) {
        if (standardNorms.has(normHeader)) continue;
        for (const [extraKey, meta] of Object.entries(EXTRA_FIELD_MAP)) {
            if (normalizeHeader(extraKey) === normHeader) {
                extraColumns.push({ normHeader, xlsxKey, meta });
                break;
            }
        }
    }

    if (extraColumns.length > 0) {
        console.log(`[Import] Detected ${extraColumns.length} extra column(s):`,
            extraColumns.map(c => `"${c.normHeader}" → ${c.meta.field}`).join(", "));
    }

    const cfg = await SalaryConfig.getSingleton();
    const rows = [];
    const errors = [];

    for (let i = 0; i < raw.length; i++) {
        const rawRow = raw[i];
        const allVals = Object.values(rawRow).map(v => String(v || "").trim());
        if (allVals.every(v => v === "")) continue;

        const row = {};
        for (const [rawHeader, fieldKey] of Object.entries(HEADER_MAP)) {
            if (fieldKey === "_skip") continue;
            const xlsxKey = normKeyMap[normalizeHeader(rawHeader)];
            row[fieldKey] = xlsxKey !== undefined ? String(rawRow[xlsxKey] ?? "").trim() : "";
        }

        const employeeNum = i + 1;
        const rowErrors = [];

        if (!row.employeeName) rowErrors.push("Employee Name is required");
        if (!row.biometricId) rowErrors.push("Biometric ID is required");
        if (!row.department) rowErrors.push("Department is required");
        if (!row.designation) rowErrors.push("Designation is required");
        if (!row.phone) rowErrors.push("Mobile Number is required");
        if (!row.gender) rowErrors.push("Gender is required");

        const nameParts = (row.employeeName || "").trim().split(/\s+/);
        const firstName = nameParts[0] || "";
        const lastName = nameParts.slice(1).join(" ") || "";

        const gross = toNum(row.grossSalary);
        const salary = recalcSalary(gross, cfg);

        const emp = {
            _employeeNum: employeeNum,
            _errors: rowErrors,
            _extraFields: extraColumns
                .map(c => ({ column: c.normHeader, field: c.meta.field, value: String(rawRow[c.xlsxKey] ?? "").trim() }))
                .filter(x => x.value),
            firstName,
            lastName,
            fatherFirstName: (row.fatherName || "").split(/\s+/)[0] || "",
            fatherLastName: (row.fatherName || "").split(/\s+/).slice(1).join(" ") || "",
            gender: normalizeEnum(row.gender, GENDER_MAP),
            dateOfBirth: parseDate(row.dateOfBirth),
            phone: row.phone || "",
            alternatePhone: row.alternatePhone || "",
            personalEmail: row.personalEmail || "",
            email: row.workEmail || "",
            maritalStatus: normalizeEnum(row.maritalStatus, MARITAL_MAP),
            bloodGroup: row.bloodGroup || "",
            nationality: row.nationality || "",
            // optBool, not toBool: an empty Yes/No cell must not flip a stored
            // true to false when this row updates an existing employee.
            isPhysicallyChallenged: optBool(row.physicallyChallenged),
            isDirector: optBool(row.isDirector),
            needsToOperate: optBool(row.needsToOperate),
            biometricId: row.biometricId || "",
            department: row.department || "",
            designation: row.designation || "",
            employmentType: normalizeEnum(row.employeeType, EMP_TYPE_MAP),
            // No default here — "GRAV Clothing" is applied only when creating.
            // Defaulting at parse time would overwrite a custom work location
            // every time someone re-imported a sheet with that column blank.
            workLocation: row.workLocation || "",
            shift: row.shift || "",
            dateOfJoining: parseDate(row.dateOfJoining),
            // Zero gross means the column was left empty. Sending a full set of
            // zeroed salary components would wipe the employee's real pay.
            salary: gross > 0 ? salary : undefined,
            bankDetails: {
                bankName: row.bankName || "",
                accountNumber: row.accountNumber || "",
                ifscCode: row.ifscCode || "",
                accountType: normalizeEnum(row.accountType, ACCT_TYPE_MAP),
                branchName: "",
            },
            documents: {
                aadharNumber: row.aadhaarNumber || "",
                panNumber: row.panNumber || "",
                uanNumber: row.uanNumber || "",
                esicNumber: row.esiNumber || "",
                pfNumber: row.pfNumber || "",
            },
            address: {
                current: {
                    street: row.currStreet || "", city: row.currCity || "",
                    state: row.currState || "", pincode: row.currPincode || "",
                    country: "India",
                },
                // Permanent is NOT mirrored from current here. It has its own
                // columns in the sheet (applied via EXTRA_FIELD_MAP), and
                // copying current over it would silently overwrite a different
                // permanent address on every re-import. The mirror still
                // happens, but only when creating a brand new employee.
            },
        };

        for (const { xlsxKey, meta } of extraColumns) {
            const rawValue = String(rawRow[xlsxKey] ?? "").trim();
            applyExtraField(emp, meta, rawValue);
        }

        rows.push(emp);
        if (rowErrors.length > 0) errors.push({ employeeNum, errors: rowErrors });
    }

    const extraDetected = extraColumns.map(c => ({ column: c.normHeader, schemaField: c.meta.field }));
    return { rows, errors, extraDetected };
};

// ─────────────────────────────────────────────────────────────────────────────
// MATCHING EXISTING EMPLOYEES
//
// An import is an upsert, not an insert. Re-importing an exported sheet — the
// obvious way to bulk-edit — used to create a second copy of everyone and then
// fail half of them on the unique index. A row that names someone already on
// record updates them instead.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Batch-resolve every row to an existing employee, returning a lookup function.
 *
 * Three queries rather than one per row, and matched in priority order:
 * Biometric ID is the sheet's identity column and is required, so it wins.
 * Identity ID and work email are fallbacks for sheets built elsewhere. They
 * are tried in sequence, never as one $or — an $or could match a DIFFERENT
 * person by email than the biometric ID names, and silently merge two records.
 */
const buildEmployeeMatcher = async (rows) => {
    const biometricIds = [...new Set(rows.map(r => r.biometricId).filter(Boolean))];
    const identityIds = [...new Set(rows.map(r => r.identityId).filter(Boolean))];
    const emails = [...new Set(rows.map(r => r.email).filter(Boolean))];

    const or = [];
    if (biometricIds.length) or.push({ biometricId: { $in: biometricIds } });
    if (identityIds.length) or.push({ identityId: { $in: identityIds } });
    if (emails.length) or.push({ email: { $in: emails } });

    const found = or.length ? await Employee.find({ $or: or }).lean() : [];

    const byBiometric = new Map();
    const byIdentity = new Map();
    const byEmail = new Map();

    for (const emp of found) {
        if (emp.biometricId) byBiometric.set(String(emp.biometricId), emp);
        if (emp.identityId) byIdentity.set(String(emp.identityId), emp);
        if (emp.email) byEmail.set(String(emp.email).toLowerCase(), emp);
    }

    return (row) => {
        if (row.biometricId && byBiometric.has(row.biometricId)) {
            return { employee: byBiometric.get(row.biometricId), matchedBy: "Biometric ID" };
        }
        if (row.identityId && byIdentity.has(row.identityId)) {
            return { employee: byIdentity.get(row.identityId), matchedBy: "Identity ID" };
        }
        const email = row.email ? String(row.email).toLowerCase() : "";
        if (email && byEmail.has(email)) {
            return { employee: byEmail.get(email), matchedBy: "Work Email" };
        }
        return null;
    };
};

