/**
 * Refuse to send anything that is not a real workbook.
 *
 * .xlsx is a zip, so a valid one always starts with the bytes "PK". A zero-byte
 * or truncated body reaches the user as Excel's "the file format or file
 * extension is not valid" with nothing anywhere to explain it — which is
 * exactly how the original broken template presented. A 500 with a message is
 * something someone can actually act on.
 */
function assertRealWorkbook(buffer, label) {
    if (!Buffer.isBuffer(buffer) || buffer.length === 0) {
        throw new Error(`Generated ${label} is empty — nothing was written.`);
    }
    if (buffer.slice(0, 2).toString("latin1") !== "PK") {
        throw new Error(
            `Generated ${label} is not a valid .xlsx (missing zip signature).`,
        );
    }
}

