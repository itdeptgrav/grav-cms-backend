/**
 * Decide what each row will do, and what it will change.
 *
 * Required-field validation only applies to rows that will CREATE someone. A
 * row updating an existing employee has already been identified, so demanding
 * Department, Designation and Gender again would block the most useful case
 * there is: a two-column sheet of Biometric ID and the one field being filled
 * in across the workforce.
 */
const planRows = async (rows) => {
    const match = await buildEmployeeMatcher(rows);

    return rows.map((row) => {
        const hit = match(row);
        const incoming = toEmployeeData(row);

        if (!hit) {
            return {
                ...row,
                _mode: "create",
                _errors: row._errors || [],
                _changes: [],
            };
        }

        // Compare against DECRYPTED salary. The stored value is a cipher string
        // and the sheet's is a number, so without this every employee would
        // look like their pay had changed on every single import.
        const existing = decryptEmployeeDoc(hit.employee);
        const { patch, changes } = buildPatch(existing, incoming);

        return {
            ...row,
            _mode: "update",
            _errors: [],                     // identity resolved; nothing else is mandatory
            _existingId: String(hit.employee._id),
            _matchedBy: hit.matchedBy,
            _existingName: [hit.employee.firstName, hit.employee.lastName]
                .filter(Boolean).join(" "),
            _changes: changes,
            _patch: patch,
        };
    });
};

